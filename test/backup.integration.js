import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, writeFile, readFile, mkdtemp, rm, readdir } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createHash } from 'node:crypto';
import os from 'node:os';
import path from 'node:path';
import mongoose from 'mongoose';
import net from 'node:net';
import { temporaryMongo } from './helpers.js';
import { loadConfig } from '../server/config.js';
import { createBackup } from '../scripts/backup.js';

test('offline backup restores synthetic MongoDB collections and original/new evidence together', async t => {
  const mongo = await temporaryMongo();
  const destination = await mkdtemp(path.join(os.tmpdir(), 'scinteg-backup-test-'));
  const connection = await mongoose.createConnection(mongo.uri).asPromise();
  t.after(async () => { await connection.close(); await mongo.stop(); await rm(destination, { recursive: true, force: true }); });
  const listener = net.createServer();
  await new Promise(resolve => listener.listen(0, '127.0.0.1', resolve));
  const port = listener.address().port;
  const config = loadConfig({ DATA_DIR: path.join(mongo.dir, 'data'), MONGODB_URI: mongo.uri, PORT: String(port) });
  await assert.rejects(createBackup({ config, backupDir: destination, offline: true }), /listener/);
  await new Promise(resolve => listener.close(resolve));
  const legacy = path.join(mongo.dir, 'old-uploads');
  await mkdir(path.join(config.dataDir, 'reports', 'synthetic'), { recursive: true });
  await mkdir(legacy);
  await writeFile(path.join(config.dataDir, 'reports', 'synthetic', 'file'), 'new original evidence');
  await writeFile(path.join(legacy, 'old.txt'), 'historical original evidence');
  await connection.db.collection('forms').insertOne({ synthetic: 'historical' });
  await connection.db.collection('submissions_v2').insertOne({ synthetic: 'new' });
  await assert.rejects(createBackup({ config, backupDir: destination }), /offline/);
  await assert.rejects(createBackup({ config, backupDir: path.join(config.dataDir, 'backup'), offline: true }), /outside/);
  const archive = await createBackup({ config, backupDir: destination, legacyUploadsDir: legacy, offline: true });
  const digest = createHash('sha256').update(await readFile(archive)).digest('hex');
  assert.ok((await readFile(`${archive}.sha256`, 'utf8')).startsWith(digest));
  const restored = path.join(destination, 'restore'); await mkdir(restored);
  const run = promisify(execFile);
  await run('tar', ['-xzf', archive, '-C', restored]);
  assert.equal(await readFile(path.join(restored, 'reports/synthetic/file'), 'utf8'), 'new original evidence');
  assert.equal(await readFile(path.join(restored, 'legacy-uploads/old.txt'), 'utf8'), 'historical original evidence');
  assert.ok(!(await readdir(restored)).includes('mongo-config.yml'));
  assert.doesNotMatch(await readFile(path.join(restored, 'manifest.json'), 'utf8'), /mongodb:\/\//);
  await run('mongorestore', ['--uri', mongo.uri.replace('/scintegform_test', '/'), '--archive=' + path.join(restored, 'database.archive.gz'), '--gzip', '--nsInclude=scintegform_test.*', '--nsFrom=scintegform_test.*', '--nsTo=restored.*']);
  const db = connection.useDb('restored').db;
  assert.equal((await db.collection('forms').findOne()).synthetic, 'historical');
  assert.equal((await db.collection('submissions_v2').findOne()).synthetic, 'new');
  assert.equal(await connection.db.collection('forms').countDocuments(), 1, 'original database untouched');
});
