import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, readdir, rm } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { simpleParser } from 'mailparser';
import { generateMailPreview } from '../scripts/dev-mail.js';

test('development preview contains real MIME report/help samples and exact email fields', async t => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'scinteg-preview-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const output = await generateMailPreview(directory);
  const names = (await readdir(path.join(directory, 'mail'))).filter(name => name.endsWith('.eml')).sort();
  assert.equal(names.length, 2);
  const report = await simpleParser(await readFile(path.join(directory, 'mail', names[0])));
  assert.deepEqual(report.from.value, [{ address: 'scinteg@tsl.ac.uk', name: 'Scinteg' }]);
  assert.deepEqual(report.to.value.map(item => item.address), ['deeks@nbi.ac.uk']);
  assert.equal(report.subject, '[TEST] Scinteg report — action required (000000000000000000000001)');
  assert.equal(report.messageId, '<scinteg-000000000000000000000001@tsl.ac.uk>');
  assert.ok(report.date instanceof Date);
  assert.equal(report.cc, undefined); assert.equal(report.bcc, undefined);
  assert.equal(report.replyTo, undefined);
  assert.equal(report.text.trim(), 'A scientific misconduct report has been submitted.\nReference: 000000000000000000000001\n\nSYNTHETIC DEVELOPMENT REPORT — not a real allegation.\nLine breaks, αβ, and <evidence> & "quotes" should survive safely.\n\nAttachments: résumé-α.txt, pixel.png');
  assert.match(report.html, /&lt;evidence&gt; &amp; &quot;quotes&quot;/);
  assert.ok(!report.html.includes('<evidence>'));
  assert.equal(report.attachments.length, 2);
  assert.equal(report.attachments[0].filename, 'résumé-α.txt');
  assert.equal(report.attachments[0].contentType, 'text/plain');
  assert.equal(report.attachments[0].content.toString(), 'Synthetic evidence only.\nUnicode: αβ café\n');
  assert.equal(report.attachments[1].filename, 'pixel.png');
  assert.equal(report.attachments[1].contentType, 'image/png');
  assert.equal(report.attachments[1].content.subarray(0, 8).toString('hex'), '89504e470d0a1a0a');
  const help = await simpleParser(await readFile(path.join(directory, 'mail', names[1])));
  assert.equal(help.subject, '[TEST] Scinteg anonymous help request (000000000000000000000002)');
  assert.equal(help.to.text, 'deeks@nbi.ac.uk');
  assert.equal(help.text.trim(), 'Anonymous help request\nReference: 000000000000000000000002\nSubject: Synthetic upload query\n\nSYNTHETIC HELP REQUEST — please ignore.\nCan you explain the attachment limits?');
  assert.equal(help.attachments.length, 0);
  const html = await readFile(output, 'utf8');
  assert.match(html, /sandbox=""/);
  assert.match(html, /Content-Security-Policy/);
  assert.match(html, /No email was sent/);
  assert.match(html, /résumé-α.txt/);
});
